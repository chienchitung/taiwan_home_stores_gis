def roc(s):
    s = s.strip()
    return f"{int(s[:-4]) + 1911}-{s[-4:-2]}-{s[-2:]}" if s else ""


def main():
    branches = {}
    for co, ban in COMPANIES.items():
        for f in (BASE / "gcis").glob(f"{ban}_*.json"):
            for r in json.loads(f.read_text(encoding="utf-8")):
                branches[(co, r["Branch_Office_Name"].strip())] = r
    verified = json.loads(VERIFIED.read_text(encoding="utf-8"))
    applied = 0
    for o in verified:
        if o["confidence"] == "confirmed" or o["store_name"] not in MAP:
            continue
        co, name = MAP[o["store_name"]]
        r = branches[(co, name)]
        date = roc(r["BR_ESTAB_DATE"])
        note = NOTES.get(o["store_name"], "")
        o.update(
            date=date, year=int(date[:4]), confidence="registry",
            sources=[f"{API}?$format=json&$filter=Business_Accounting_NO eq {COMPANIES[co]}"],
            evidence=(f"經濟部商工登記：{co}（統編 {COMPANIES[co]}）{name}，分公司核准設立日 {date}，"
                      f"地址 {r['Branch_Office_Location'].strip()}；查無開幕新聞，以登記日代表開店日"
                      + (f"（{note}）" if note else "")),
        )
        applied += 1
    VERIFIED.write_text(json.dumps(verified, ensure_ascii=False, indent=1), encoding="utf-8")
    print(f"applied {applied}")


if __name__ == "__main__":
    main()
