CITIES = ("台北市", "新北市", "桃園市", "台中市", "台南市", "高雄市", "基隆市", "新竹市", "嘉義市", "新竹縣", "花蓮縣", "屏東縣")


def region_for(city):
    if city in {"台北市", "新北市", "基隆市", "桃園市", "新竹市", "新竹縣", "苗栗縣"}:
        return "北部"
    if city in {"台中市", "彰化縣", "南投縣", "雲林縣"}:
        return "中部"
    if city in {"嘉義市", "嘉義縣", "台南市", "高雄市", "屏東縣"}:
        return "南部"
    return "東部/離島"


DISTRICT_OVERRIDES = {"台中市自由路三段48號（當時門牌）": "中區"}  # 自由路與中正路（今台灣大道）口位於中區


def split_address(address):
    city = next(c for c in CITIES if address.startswith(c))
    rest = address[len(city):]
    # 先找「區」（避免「前鎮區」被切成「前鎮」），縣轄市／鄉鎮再找「市鄉鎮」
    m = re.match(r"(.{1,3}?區)", rest) or re.match(r"(.{1,3}?[市鄉鎮])", rest)
    if not m:
        # 舊門牌未寫行政區（遠百舊台中店），以其路口描述所在行政區為準
        return city, DISTRICT_OVERRIDES[address]
    return city, m.group(1)


