    # 新門市編號接在所有既有資料（含本次替換的品牌）之後，避免和沿用舊編號的門市重複
    next_n = max(int(r.get("n") or 0) for r in rows) + 1
    stores = []
    for brand, name, address, lat, lng, opened, status, note, wiki, coord_src in STORES:
        full = f"{brand} {name}" if not name.startswith(brand) else name
        city, district = split_address(address)
        n = old_n.get(full)
        if n is None:
            n, next_n = next_n, next_n + 1
        stores.append({
            "brand": brand, "store_name": full, "store_type": "百貨公司",
            "region": region_for(city), "city": city, "address": address,
            "opened_date": opened, "status": status, "note": note, "district": district,
            "channel_format": "百貨商場 / 購物中心",
            "status_category": "現行營運中" if status == "營業中" else "暫停營業",
            "lat": lat, "lng": lng, "geocode_score": 100,
            "clean_address": address, "clean_name": full, "clean_query": f"{full} {address}",
            "is_co_location": False, "source_url": WIKI + wiki,
            "coordinate_source": coord_src + "（2026-10-22 查核）",
            "google_maps_url": "https://www.google.com/maps/search/?api=1&query=" + quote(f"{full} {address}"),
            "verification_status": "維基百科分店清單；Google 地圖與國土測繪中心行政區已交叉核對",
            "n": n, "opened_date_source": WIKI + wiki if opened else "",
            "opened_date_basis": "新聞／官方" if opened else "",
        })
    all_rows = kept + stores
    MAIN_JSON.write_text(json.dumps(all_rows, ensure_ascii=False, indent=2), encoding="utf-8")
    fields = list(dict.fromkeys(k for r in all_rows for k in r))
    with open(MAIN_CSV, "w", encoding="utf-8-sig", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=fields)
        writer.writeheader()
        writer.writerows(all_rows)

    raw = VERIFIED_JSON.read_text(encoding="utf-8")
    verified = [v for v in json.loads(raw) if v["brand"] not in BRANDS]
    for s in stores:
        if s["opened_date"]:
            verified.append({
                "brand": s["brand"], "store_name": s["store_name"], "date": s["opened_date"],
                "year": int(s["opened_date"][:4]), "confidence": "confirmed", "sources": [s["source_url"]],
                "evidence": f"維基百科分店表「開幕」欄：{s['opened_date']}" + (f"；{s['note']}" if s["note"] else ""),
            })
    VERIFIED_JSON.write_text(json.dumps(verified, ensure_ascii=False, indent=2) + ("\n" if raw.endswith("\n") else ""),
                             encoding="utf-8")
    print(f"百貨公司 {len(stores)} 間：" + "、".join(f"{b} {sum(s['brand'] == b for s in stores)}" for b in BRANDS))


